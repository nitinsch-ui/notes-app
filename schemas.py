# SYNTAX: BaseModel is Pydantic's core class — any class inheriting from it
#         gets automatic type validation and JSON conversion for free.
# FUNCTION: these classes define the API's CONTRACT — exactly what shape of
#           data comes in and goes out — kept deliberately separate from
#           the SQLAlchemy models in models.py (which define what's stored).
from pydantic import BaseModel
from datetime import datetime
from typing import Optional


class CategoryCreate(BaseModel):
    # SYNTAX: `name: str` is a type-annotated field — Pydantic will reject
    #         a request where "name" isn't a string.
    # FUNCTION: this is what a client must send to POST /categories.
    #           No `id` here — the client doesn't get to invent that,
    #           the database generates it.
    name: str


class CategoryOut(BaseModel):
    # FUNCTION: this is what the API sends BACK after creating/fetching a
    #           category — includes id, since the client wants to see it.
    id: int
    name: str


    class Config:
        # SYNTAX: from_attributes = True (Pydantic v2) tells Pydantic it's
        #         allowed to build this object by reading attributes off
        #         a plain Python object (like a SQLAlchemy Category
        #         instance), not just from a dict.
        # FUNCTION: this is what lets `return db_category` in main.py work
        #           directly — FastAPI converts the SQLAlchemy object into
        #           this schema automatically, using response_model.
        from_attributes = True


class NoteCreate(BaseModel):
    # FUNCTION: shape required to create a note. Notice: no `id` and no
    #           `created_at` — those are generated by the database, not
    #           supplied by the client. This asymmetry between "what you
    #           send" and "what you get back" is exactly why NoteCreate
    #           and NoteOut are two separate classes, not one.
    title: str
    content: str
    category_id: int


class NoteOut(BaseModel):
    # FUNCTION: full shape returned to the client — includes the
    #           database-generated id and created_at.
    id: int
    title: str
    content: str
    category_id: int
    created_at: datetime


    class Config:
        from_attributes = True


class NoteUpdate(BaseModel):
    # SYNTAX: `str | None = None` means this field is OPTIONAL — if the
    #         client's JSON doesn't include it, it defaults to None here.
    # FUNCTION: used for PATCH (partial update). Every field is optional
    #           because a PATCH request might only want to change ONE
    #           field (e.g. just the title) without touching the rest —
    #           that's the defining difference between PATCH and PUT.
    title: Optional[str] = None
    content: Optional[str] = None
    category_id: Optional[int] = None


